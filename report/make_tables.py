r"""Render results from experiments/results/summary.json into LaTeX macros/tables.

    py -3.13 report/make_tables.py

The generated report/tables.tex is \input by report.tex, so the report never
contains hand-typed experimental numbers.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SUMMARY = ROOT / "experiments" / "results" / "summary.json"
OUT = ROOT / "report" / "tables.tex"


def f(value, digits=3):
    if isinstance(value, (int, float)):
        return f"{value:.{digits}f}"
    return "n/a"


def esc(text) -> str:
    return str(text).replace("_", "\\_").replace("&", "\\&").replace("%", "\\%")


def build():
    data = json.loads(SUMMARY.read_text(encoding="utf-8")) if SUMMARY.exists() else {}
    exps = data.get("experiments", [])
    test = data.get("test", {})
    scaled = test.get("temperature_scaled", {})
    raw = test.get("raw_softmax", {})
    abst = test.get("abstention_on_test", {})
    complexity = test.get("complexity", {})
    per_class = test.get("per_class", {})
    top_confusions = test.get("top_confusions", [])
    confusion_text = ", ".join(f"{esc(a)}$\\to${esc(b)} ({n})"
                               for a, b, n in top_confusions) or "n/a"

    lines = [
        "% AUTO-GENERATED by report/make_tables.py — do not edit by hand.",
        "\\newcommand{\\selectedModel}{" + esc(data.get("selected_model", {}).get("name", "n/a")) + "}",
        "\\newcommand{\\testAcc}{" + f(scaled.get("accuracy")) + "}",
        "\\newcommand{\\testFone}{" + f(scaled.get("f1_macro")) + "}",
        "\\newcommand{\\testPrecision}{" + f(scaled.get("precision_macro")) + "}",
        "\\newcommand{\\testRecall}{" + f(scaled.get("recall_macro")) + "}",
        "\\newcommand{\\eceBefore}{" + f(test.get("ece_before")) + "}",
        "\\newcommand{\\eceAfter}{" + f(test.get("ece_after")) + "}",
        "\\newcommand{\\abstTau}{" + f(abst.get("threshold"), 2) + "}",
        "\\newcommand{\\abstCoverage}{" + f(abst.get("coverage")) + "}",
        "\\newcommand{\\abstAccuracy}{" + f(abst.get("accuracy_on_answered")) + "}",
        "\\newcommand{\\finalParams}{" + f"{complexity.get('params_total', 'n/a')}" + "}",
        "\\newcommand{\\finalLatency}{" + f(test.get("latency_ms"), 1) + "}",
        "\\newcommand{\\topConfusions}{" + confusion_text + "}",
        "", "% ---------- experiment matrix ----------",
        "\\newcommand{\\experimentTable}{%",
        "\\begin{table}[htbp]\\centering",
        "\\caption{Controlled experiment matrix. Model selection uses validation accuracy only;",
        "the test set is evaluated once after all decisions are frozen.}",
        "\\label{tab:experiments}",
        "\\begin{tabular}{llcccc}", "\\toprule",
        "ID & Model & Val acc & Val F1 & Params & ms/image \\\\", "\\midrule",
    ]
    for e in exps:
        lines.append(f"{esc(e['id'])} & {esc(e['name'])} & {f(e['val_accuracy'])} & "
                     f"{f(e['val_f1_macro'])} & {e.get('params','n/a')} & "
                     f"{f(e.get('latency_ms'),1)} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}}", ""]

    lines += ["% ---------- final test metrics ----------",
              "\\newcommand{\\finalTable}{%",
              "\\begin{table}[htbp]\\centering",
              "\\caption{Final evaluation on the untouched test set (temperature-scaled probabilities).}",
              "\\label{tab:final}",
              "\\begin{tabular}{lc}\\toprule", "Metric & Value \\\\", "\\midrule",
              f"Accuracy & {f(scaled.get('accuracy'))} \\\\",
              f"Macro precision & {f(scaled.get('precision_macro'))} \\\\",
              f"Macro recall & {f(scaled.get('recall_macro'))} \\\\",
              f"Macro F1 & {f(scaled.get('f1_macro'))} \\\\",
              f"ECE before calibration & {f(test.get('ece_before'))} \\\\",
              f"ECE after calibration & {f(test.get('ece_after'))} \\\\",
              f"Latency (ms / image) & {f(test.get('latency_ms'),1)} \\\\",
              f"Parameters & {complexity.get('params_total','n/a')} \\\\",
              f"Model size (MB) & {complexity.get('size_mb','n/a')} \\\\",
              "\\bottomrule", "\\end{tabular}", "\\end{table}}", ""]

    lines += ["% ---------- per-class ----------",
              "\\newcommand{\\perClassTable}{%",
              "\\begin{table}[htbp]\\centering",
              "\\caption{Per-class precision, recall and F1 on the test set.}",
              "\\label{tab:perclass}",
              "\\begin{tabular}{lccc}\\toprule",
              "Category & Precision & Recall & F1 \\\\", "\\midrule"]
    for name, metrics in per_class.items():
        lines.append(f"{esc(name)} & {f(metrics.get('precision'))} & "
                     f"{f(metrics.get('recall'))} & {f(metrics.get('f1-score'))} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}}", ""]

    robust = data.get("robustness", {})
    lines += ["% ---------- robustness ----------",
              "\\newcommand{\\robustAcc}{" + f(robust.get("accuracy")) + "}",
              "\\newcommand{\\robustFone}{" + f(robust.get("macro_f1")) + "}",
              "\\newcommand{\\robustConf}{" + f(robust.get("mean_confidence")) + "}",
              "\\newcommand{\\robustImages}{" + str(robust.get("images", "n/a")) + "}",
              "\\newcommand{\\robustTable}{%",
              "\\begin{table}[htbp]\\centering",
              "\\caption{Cross-dataset robustness on a fixed RealWaste subset "
              "(distribution shift from studio to landfill photos).}",
              "\\label{tab:robust}",
              "\\begin{tabular}{lc}\\toprule", "Quantity & Value \\\\", "\\midrule",
              f"Images evaluated & {robust.get('images','n/a')} \\\\",
              f"Accuracy & {f(robust.get('accuracy'))} \\\\",
              f"Macro F1 & {f(robust.get('macro_f1'))} \\\\",
              f"Mean confidence & {f(robust.get('mean_confidence'))} \\\\",
              "\\bottomrule", "\\end{tabular}", "\\end{table}}", ""]

    lines += ["% ---------- abstention ----------",
              "\\newcommand{\\abstentionTable}{%",
              "\\begin{table}[htbp]\\centering",
              "\\caption{Abstention behaviour on the test set at the validation-chosen threshold.}",
              "\\label{tab:abstain}",
              "\\begin{tabular}{lc}\\toprule", "Quantity & Value \\\\", "\\midrule",
              f"Confidence threshold $\\tau$ & {f(abst.get('threshold'),2)} \\\\",
              f"Coverage (fraction answered) & {f(abst.get('coverage'))} \\\\",
              f"Accuracy on answered images & {f(abst.get('accuracy_on_answered'))} \\\\",
              f"Images flagged for manual review & {abst.get('flagged_for_review','n/a')} \\\\",
              "\\bottomrule", "\\end{tabular}", "\\end{table}}", ""]

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    build()
